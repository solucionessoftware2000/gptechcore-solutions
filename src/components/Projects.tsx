import {
  ArrowUpRight,
  Brain,
  Circle,
  ClipboardCheck,
  Clock,
  Cloud,
  FileText,
  Heart,
  Landmark,
  Lock,
  MonitorCheck,
  QrCode,
  Scale,
  Shield,
  Smartphone,
  Wifi,
  Workflow,
  type LucideIcon,
} from 'lucide-react';
import Reveal from './Reveal';
import projectsData from '../data/projects.json';

type Project = {
  id: string;
  logo: string;
  name: string;
  domain: string;
  href: string;
  image?: string;
  description: string;
  pills: { icon: string; label: string }[];
  tags: string[];
  featured?: boolean;
};

type ProjectStatus = {
  checkedAt?: string;
  projects?: Record<string, { up?: boolean; reason?: string }>;
};

// Pill icons referenced by name in projects.json; add new ones here explicitly to keep tree-shaking
const iconMap = {
  Brain,
  ClipboardCheck,
  Clock,
  Cloud,
  FileText,
  Heart,
  Landmark,
  Lock,
  MonitorCheck,
  QrCode,
  Scale,
  Shield,
  Smartphone,
  Wifi,
  Workflow,
} satisfies Record<string, LucideIcon>;

function getIcon(name: string): LucideIcon {
  if (Object.prototype.hasOwnProperty.call(iconMap, name)) return iconMap[name as keyof typeof iconMap];
  if (import.meta.env.DEV) console.warn(`[Projects] Unknown pill icon "${name}", using fallback`);
  return Circle;
}

// Generated by `npm run check:projects` (CI only, gitignored). Missing file = show every project.
const statusModules = import.meta.glob<ProjectStatus>('../data/project-status.json', {
  eager: true,
  import: 'default',
});
const projectStatus: ProjectStatus | undefined = Object.values(statusModules)[0];

const projects: Project[] = projectsData;
const visibleProjects = projects.filter((project) => projectStatus?.projects?.[project.id]?.up !== false);

// With an odd number of regular cards, the last one is centered at half width instead of left orphaned
const regularIds = visibleProjects.filter((project) => !project.featured).map((project) => project.id);
const orphanId = regularIds.length % 2 === 1 ? regularIds[regularIds.length - 1] : undefined;

function layoutClass(project: Project) {
  if (project.featured) return 'sm:col-span-2';
  if (project.id === orphanId) return 'sm:col-span-2 sm:justify-self-center sm:w-[calc(50%-0.625rem)]';
  return '';
}

// Same faint grid texture used behind the hero
const gridTexture = {
  backgroundImage:
    'linear-gradient(rgba(255,255,255,0.6) 1px, transparent 1px), linear-gradient(90deg, rgba(255,255,255,0.6) 1px, transparent 1px)',
  backgroundSize: '48px 48px',
};

export default function Projects() {
  // Nothing reachable: drop the whole section rather than show an empty header
  if (visibleProjects.length === 0) return null;

  return (
    <section id="proyectos" className="section-padding relative bg-ink-800">
      <div className="container-landing">
        <Reveal className="text-center mb-16">
          <p className="text-sm font-semibold text-mint-400 font-mono tracking-widest uppercase mb-3">
            // Proyectos
          </p>
          <h2 className="text-3xl sm:text-4xl font-bold text-white tracking-tight">
            Proyectos que hemos entregado
          </h2>
          <p className="mt-4 text-ink-100 max-w-2xl mx-auto">
            Landing pages, plataformas con pagos y un sistema municipal de trámites. Cada tarjeta muestra qué construimos y con qué tecnología.
          </p>
        </Reveal>

        <div className="grid sm:grid-cols-2 gap-5 max-w-4xl mx-auto">
          {visibleProjects.map((project, index) => (
            <Reveal key={project.id} delay={index * 60} className={`h-full ${layoutClass(project)}`}>
              <div className="group h-full rounded-2xl border border-white/[0.08] bg-white/[0.02] backdrop-blur-sm overflow-hidden hover:-translate-y-1 hover:border-white/[0.16] hover:bg-white/[0.04] hover:shadow-2xl hover:shadow-mint-500/5 transition-[transform,box-shadow,border-color,background-color] duration-200 ease-out-binance flex flex-col">
                {/* Preview: real screenshot when available, branded panel otherwise */}
                <div
                  className={`relative shrink-0 overflow-hidden border-b border-white/[0.08] bg-ink-800 aspect-[16/10] ${
                    project.featured ? 'sm:aspect-[21/9]' : ''
                  }`}
                >
                  {project.image ? (
                    <img
                      src={`${import.meta.env.BASE_URL}${project.image}`}
                      alt={`Página de inicio de ${project.name} (${project.domain}), proyecto desarrollado por GPTech Core`}
                      width={1200}
                      height={750}
                      loading="lazy"
                      decoding="async"
                      className="absolute inset-0 w-full h-full object-cover object-top transition-transform duration-500 ease-out-expo motion-safe:group-hover:scale-[1.03]"
                    />
                  ) : (
                    <div
                      aria-hidden="true"
                      className="absolute inset-0 bg-gradient-to-br from-ink-700 via-brand-950 to-ink-700 flex flex-col items-center justify-center gap-2 transition-transform duration-500 ease-out-expo motion-safe:group-hover:scale-[1.03]"
                    >
                      <div className="absolute inset-0 opacity-[0.07] pointer-events-none" style={gridTexture} />
                      <span className="relative text-4xl sm:text-5xl font-bold font-mono tracking-tight text-white">
                        {project.logo}
                      </span>
                      <span className="relative text-xs text-ink-100 font-mono">$ {project.domain}</span>
                    </div>
                  )}
                </div>

                <div className="p-5 flex flex-col flex-1">
                  <div className="flex items-center justify-between mb-3">
                    <div className="flex items-center gap-3">
                      <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-brand-500 to-brand-700 flex items-center justify-center shadow-sm shadow-brand-500/20 shrink-0">
                        <span className="text-white font-bold text-sm">{project.logo}</span>
                      </div>
                      <div>
                        <h3 className="text-base font-bold text-white leading-tight">{project.name}</h3>
                        <p className="text-xs text-ink-100 font-mono">$ {project.domain}</p>
                      </div>
                    </div>
                    <span className="text-[10px] font-mono text-white/30 tracking-widest">
                      P{String(index + 1).padStart(2, '0')}
                    </span>
                  </div>

                  <p className="text-sm text-ink-100 leading-relaxed mb-4">{project.description}</p>

                  <div className="flex flex-wrap gap-1.5 mb-4">
                    {project.pills.map(({ icon, label }) => {
                      const Icon = getIcon(icon);
                      return (
                        <span
                          key={label}
                          className="inline-flex items-center gap-1 px-2.5 py-1 rounded-full bg-mint-500/10 text-mint-400 text-xs font-medium border border-mint-400/20"
                        >
                          <Icon className="w-3 h-3" />
                          {label}
                        </span>
                      );
                    })}
                  </div>

                  <div className="flex-1" />

                  <div className="flex flex-wrap gap-1.5 mb-4">
                    {project.tags.map((tag) => (
                      <span
                        key={tag}
                        className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded border border-white/10 bg-white/[0.03] text-[10px] font-mono text-white/50 tracking-wide"
                      >
                        <span className="w-1 h-1 rounded-full bg-mint-400/70" />
                        {tag}
                      </span>
                    ))}
                  </div>

                  <a
                    href={project.href}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex items-center justify-center gap-1.5 px-3 py-2.5 rounded-lg border border-white/10 text-white text-sm font-medium hover:border-mint-400/40 hover:bg-mint-500/10 hover:text-mint-400 active:scale-[0.97] transition-[background-color,border-color,color,transform] duration-150 ease-out-binance"
                  >
                    Ver sitio
                    <ArrowUpRight className="w-4 h-4" />
                  </a>
                </div>
              </div>
            </Reveal>
          ))}
        </div>
      </div>
    </section>
  );
}
